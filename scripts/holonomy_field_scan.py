# per-loop analysis


def analyze_state(rec, working=WORKING_DIGITS, verify=VERIFY_DIGITS):
    cf = rec["closed_form"]
    dets = [tuple(t) for t in cf["support_dets"]]
    M, d = incidence(dets)
    basis, saturated = loop_basis(M)
    if not basis:
        return []
    amps = [sp.sympify(p) for p in cf["pretty"]]
    phases = [sp.arg(a) for a in amps]
    weights = cf["weights"]
    den = cf["den"]
    rational_weights = all(isinstance(w, int) for w in weights)

    rows = []
    for li, k in enumerate(basis):
        Phi = sp.simplify(sum(k[i] * phases[i] for i in range(len(k))))
        cos_exact = sp.simplify(sp.expand_trig(sp.cos(Phi)))
        cos_exact = sp.radsimp(sp.sqrtdenest(sp.nsimplify(cos_exact)))

        # numeric cross-check of the symbolic simplification
        mp.mp.dps = working + 15
        direct = sp.N(sp.cos(sum(k[i] * phases[i] for i in range(len(k)))), working)
        simplified = sp.N(cos_exact, working)
        agree = abs(sp.Float(direct) - sp.Float(simplified)) < sp.Float(10) ** (-(working - 10))

        mpoly = sp.Poly(sp.minimal_polynomial(cos_exact, x), x)
        degree = mpoly.degree()
        exact_coeffs = [int(c) for c in reversed(mpoly.all_coeffs())]
        if exact_coeffs[-1] < 0:
            exact_coeffs = [-c for c in exact_coeffs]

        pslq = pslq_minpoly(cos_exact, working, verify)
        pslq_agrees = bool(pslq) and pslq["coeffs_ascending"] == exact_coeffs

        if degree == 1:
            gname, two_elem, gorder = "C1", True, 1
        else:
            G, _ = galois_group(mpoly)
            gname, two_elem, gorder = group_name(G), is_two_elementary(G), int(G.order())

        rads = radicands(cos_exact)
        memberships = []
        if rads is not None and rational_weights:
            for rad in rads:
                ok, expo = in_weight_group(rad, weights, den)
                memberships.append({"radicand": rad, "in_weight_group": ok, "exponents_f2": expo})

        rows.append(
            {
                "system": rec["system"],
                "index": rec["index"],
                "loop": li,
                "support_size": len(dets),
                "kernel_vector": k,
                "active_dets": [list(dets[i]) for i in range(len(k)) if k[i] != 0],
                "loops_in_state": len(basis),
                "kernel_saturated": saturated,
                "holonomy_exact": sp.srepr(Phi) if Phi.free_symbols else str(Phi),
                "cos_exact": str(cos_exact),
                "cos_numeric_30": str(sp.N(cos_exact, 30)),
                "symbolic_numeric_agree": bool(agree),
                "min_poly": str(mpoly.as_expr()),
                "min_poly_coeffs_ascending": exact_coeffs,
                "degree": degree,
                "galois_group": gname,
                "galois_order": gorder,
                "two_elementary": bool(two_elem),
                "pslq": pslq,
                "pslq_confirms_exact": pslq_agrees,
                "radicands": rads,
                "multiquadratic_witness": rads is not None,
                "radicand_weight_group": memberships,
                "weights": weights,
                "den": den,
                "rational_weights": rational_weights,
            }
        )
    return rows


