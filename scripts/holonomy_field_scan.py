# arithmetic helpers


def squarefree_class(n: int) -> dict[int, int]:
    """Prime exponent vector mod 2 of a positive integer, as {prime: 1}."""
    cls = {}
    for p, e in sp.factorint(sp.Integer(abs(n))).items():
        if e % 2:
            cls[int(p)] = 1
    return cls


def squarefree_part(n: int) -> int:
    """Positive squarefree kernel of |n|, the representative of its class in
    Q*/(Q*)^2."""
    sf = 1
    for p, e in sp.factorint(sp.Integer(abs(n))).items():
        if e % 2:
            sf *= int(p)
    return sf


def radicands(expr):
    """Squarefree radicands of every square root appearing in expr.

    Returns a sorted list, or None if the expression is not built purely from
    rationals, sums, products and square roots of rationals. A non-None return
    is a syntactic witness that the value lies in a multiquadratic extension of
    Q, independent of the Galois group computation.
    """
    found: set[int] = set()

    def walk(e) -> bool:
        if e.is_Rational:
            return True
        if e.is_Add or e.is_Mul:
            return all(walk(a) for a in e.args)
        if e.is_Pow:
            base, power = e.args
            if base.is_Rational and power.is_Rational and abs(power.q) == 2:
                r = sp.Rational(base)
                # sqrt(a/b) and sqrt(a*b) generate the same quadratic field
                sf = squarefree_part(int(r.p) * int(r.q))
                if sf > 1:
                    found.add(sf)
                return True
            return False
        return False

    # walk the expression as given; retry once on a denested form. nsimplify is
    # deliberately NOT used here: it re-nests (sqrt(2) - sqrt(42))/8 back into
    # sqrt(11/16 - sqrt(21)/16), which hides the multiquadratic witness.
    for candidate in (sp.expand(expr), sp.sqrtdenest(sp.expand(expr))):
        found.clear()
        if walk(candidate):
            return sorted(found)
    return None


def in_weight_group(radicand: int, weights: list[int], den: int):
    """Is the class of `radicand` in Q*/(Q*)^2 generated by the weights and den?

    Returns (bool, exponent list over [weights..., den]) via F2 linear algebra
    on prime exponent vectors. This is the "square roots of rational monomials
    in the weights" clause of the Holonomy Rationality conjecture, tested
    rather than assumed.
    """
    gens = [int(w) for w in weights] + [int(den)]
    primes = set()
    for g in gens + [radicand]:
        primes |= set(squarefree_class(abs(g)))
    primes = sorted(primes)
    if not primes:
        return True, [0] * len(gens)
    cols = []
    for g in gens:
        c = squarefree_class(abs(g))
        cols.append([c.get(p, 0) for p in primes])
    tgt = squarefree_class(abs(radicand))
    target = [tgt.get(p, 0) for p in primes]
    # Gaussian elimination over F2 on the matrix whose columns are cols.
    rows = len(primes)
    aug = [[cols[j][i] for j in range(len(gens))] + [target[i]] for i in range(rows)]
    pivots = []
    r = 0
    for c in range(len(gens)):
        pr = next((i for i in range(r, rows) if aug[i][c]), None)
        if pr is None:
            continue
        aug[r], aug[pr] = aug[pr], aug[r]
        for i in range(rows):
            if i != r and aug[i][c]:
                aug[i] = [(a ^ b) for a, b in zip(aug[i], aug[r])]
        pivots.append(c)
        r += 1
        if r == rows:
            break
    for i in range(r, rows):
        if aug[i][-1]:
            return False, None
    expo = [0] * len(gens)
    for i, c in enumerate(pivots):
        expo[c] = aug[i][-1]
    return True, expo


def group_name(G) -> str:
    """Readable name for the small Galois groups that occur here."""
    n = G.order()
    if n == 1:
        return "C1"
    if n == 2:
        return "C2"
    elementary = all(g.order() in (1, 2) for g in G.elements)
    if n == 4:
        return "V4" if elementary else "C4"
    if G.is_abelian:
        return f"A{n}(elementary)" if elementary else f"A{n}"
    return f"nonabelian order {n}"


def is_two_elementary(G) -> bool:
    """G isomorphic to (Z/2)^k: abelian of exponent dividing 2."""
    n = G.order()
    if n & (n - 1):
        return False
    return G.is_abelian and all(g.order() in (1, 2) for g in G.elements)


# --------------------------------------------------------------------------
# PSLQ with the mandatory double-precision re-verification


def to_mpf(expr, digits: int):
    """Evaluate an exact real algebraic expression to `digits` decimals as an
    mpmath float, going through sympy's arbitrary-precision evaluator."""
    return mp.mpf(str(sp.N(expr, digits)))


def pslq_minpoly(value_expr, working: int, verify: int, max_degree: int = MAX_PSLQ_DEGREE):
    """Recognize an integer relation on powers of a real algebraic number.

    Searches increasing degree at `working` digits, then RE-VERIFIES the hit at
    `verify` digits (>= 2 * working by convention). Returns a dict including
    the residual at the verification precision, or None if nothing survives.

    Acceptance: log10(residual) <= -(working + verify) / 2. A genuine relation
    lands near 10^-verify; a spurious one stalls near 10^-working. The midpoint
    separates them with a wide margin at the precisions used here.
    """
    mp.mp.dps = working + 15
    val = to_mpf(value_expr, working + 25)
    tol = mp.mpf(10) ** (-(working - 8))

    # PSLQ needs a vector of nonzero numbers, so a vanishing holonomy cosine is
    # recognized directly: the relation is x, re-verified the same way.
    if abs(val) < tol:
        mp.mp.dps = verify + 15
        residual = abs(to_mpf(value_expr, verify + 25))
        mp.mp.dps = working + 15
        if residual >= mp.mpf(10) ** (-(working + verify) // 2):
            return None
        return {
            "degree": 1,
            "coeffs_ascending": [0, 1],
            "residual": mp.nstr(residual, 6),
            "residual_log10": (
                float(mp.log(residual, 10)) if residual > 0 else float("-inf")
            ),
            "working_digits": working,
            "verify_digits": verify,
        }

    for n in range(1, max_degree + 1):
        rel = mp.pslq(
            [val**j for j in range(n + 1)],
            maxcoeff=MAX_PSLQ_COEFF,
            maxsteps=10**6,
            tol=tol,
        )
        if not rel:
            continue
        if rel[-1] == 0:  # degenerate: relation lives at a lower degree
            continue
        mp.mp.dps = verify + 15
        v2 = to_mpf(value_expr, verify + 25)
        residual = abs(sum(mp.mpf(rel[j]) * v2**j for j in range(n + 1)))
        threshold = mp.mpf(10) ** (-(working + verify) // 2)
        accepted = residual < threshold
        mp.mp.dps = working + 15
        if not accepted:
            # protocol: a relation that fails re-verification is deleted.
            continue
        coeffs = [int(c) for c in rel]
        if coeffs[-1] < 0:
            coeffs = [-c for c in coeffs]
        return {
            "degree": n,
            "coeffs_ascending": coeffs,
            "residual": mp.nstr(residual, 6),
            "residual_log10": (
                float(mp.log(residual, 10)) if residual > 0 else float("-inf")
            ),
            "working_digits": working,
            "verify_digits": verify,
        }
    return None


