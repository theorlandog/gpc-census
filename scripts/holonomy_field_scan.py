WORKING_DIGITS = 120
VERIFY_DIGITS = 240
MAX_PSLQ_DEGREE = 8
MAX_PSLQ_COEFF = 10**24


# --------------------------------------------------------------------------
# ledger


def load_states(path: Path = LEDGER):
    return [json.loads(ln) for ln in path.read_text().splitlines() if ln.strip()]


def incidence(dets):
    """Support incidence matrix M, rows = determinants, cols = orbitals."""
    d = max(m for T in dets for m in T) + 1
    return sp.Matrix([[1 if m in T else 0 for m in range(d)] for T in dets]), d


def loop_basis(M):
    """Primitive integer basis of the integer left kernel of M, with a proof
    that it is saturated (generates the full lattice, not a finite-index
    sublattice). Returns (basis, saturated)."""
    basis = []
    for u in M.T.nullspace():
        u = u * sp.lcm([q.q for q in u])
        u = u / sp.gcd([sp.Integer(q) for q in u])
        v = [int(q) for q in u]
        lead = next((c for c in v if c != 0), 1)
        if lead < 0:
            v = [-c for c in v]
        basis.append(v)
    if not basis:
        return [], True
    saturated = all(f == 1 for f in invariant_factors(sp.Matrix(basis)))
    return basis, bool(saturated)


