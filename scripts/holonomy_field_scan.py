# driver


def build(working=WORKING_DIGITS, verify=VERIFY_DIGITS, only=None):
    rows = []
    for rec in load_states():
        if rec["classified"] != "INTERFERENCE":
            continue
        if only and (rec["system"], rec["index"]) != only:
            continue
        rows.extend(analyze_state(rec, working, verify))

    states = sorted({(r["system"], r["index"]) for r in rows})
    degrees = {}
    groups = {}
    for r in rows:
        degrees[str(r["degree"])] = degrees.get(str(r["degree"]), 0) + 1
        groups[r["galois_group"]] = groups.get(r["galois_group"], 0) + 1

    summary = {
        "loopy_states": len(states),
        "loops": len(rows),
        "degree_counts": dict(sorted(degrees.items(), key=lambda kv: int(kv[0]))),
        "galois_group_counts": dict(sorted(groups.items())),
        "all_degrees_in_1_2_4": all(r["degree"] in (1, 2, 4) for r in rows),
        "all_two_elementary": all(r["two_elementary"] for r in rows),
        "all_kernels_saturated": all(r["kernel_saturated"] for r in rows),
        "all_symbolic_numeric_agree": all(r["symbolic_numeric_agree"] for r in rows),
        "all_pslq_reverified": all(r["pslq"] is not None for r in rows),
        "all_pslq_confirm_exact": all(r["pslq_confirms_exact"] for r in rows),
        "all_multiquadratic_witnessed": all(r["multiquadratic_witness"] for r in rows),
        "all_radicands_in_weight_group": all(
            all(m["in_weight_group"] for m in r["radicand_weight_group"])
            for r in rows
            if r["rational_weights"]
        ),
        "loops_with_radicand_outside_weight_group": sum(
            1
            for r in rows
            if any(not m["in_weight_group"] for m in r["radicand_weight_group"])
        ),
        "worst_pslq_residual_log10": max(
            (r["pslq"]["residual_log10"] for r in rows if r["pslq"]), default=None
        ),
    }
    summary["weight_group_note"] = (
        "all_radicands_in_weight_group tests the STRONGER sub-clause of the "
        "Holonomy Rationality conjecture, that every adjoined square root is of "
        "a rational MONOMIAL in the weights. It is false: "
        f"{summary['loops_with_radicand_outside_weight_group']} of {len(rows)} "
        "loops adjoin a square root whose squarefree class is outside the group "
        "generated by the weights and the denominator. The mechanism is the "
        "quadratic formula: solving A cos(Phi) + B sin(Phi) + C = 0 adjoins "
        "sqrt(A^2 + B^2 - C^2), a POLYNOMIAL and not a monomial in the weight "
        "data, and later loops see the sines of earlier ones. The conjecture's "
        "actual conclusion, that the field is multiquadratic, is unaffected and "
        "holds on every loop. See docs/holonomy_rationality.md."
    )
    return {
        "generated_by": "scripts/holonomy_field_scan.py",
        "ledger": "results/data/states.jsonl",
        "what": (
            "Gauge-invariant loop holonomy cosines of every certified "
            "INTERFERENCE state whose support carries loops, with the number "
            "field each generates."
        ),
        "precision_protocol": {
            "working_digits": working,
            "verify_digits": verify,
            "rule": (
                "Every PSLQ-recognized relation is re-verified at the "
                "verification precision and accepted only if its residual is "
                "below 10^-((working+verify)/2). A relation that fails "
                "re-verification is deleted, not downgraded."
            ),
            "evidence": "see --precision-lesson and the precision_lesson block",
        },
        "summary": summary,
        "trisection_audit": trisection_audit(rows),
        "precision_lesson": precision_lesson(),
        "loops": rows,
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--digits", type=int, default=WORKING_DIGITS)
    ap.add_argument("--verify-digits", type=int, default=VERIFY_DIGITS)
    ap.add_argument("--system")
    ap.add_argument("--index", type=int)
    ap.add_argument("--stdout", action="store_true", help="print instead of writing")
    ap.add_argument("--check", action="store_true", help="fail if the artifact is stale")
    ap.add_argument("--precision-lesson", action="store_true")
    a = ap.parse_args()

    if a.precision_lesson:
        print(json.dumps(precision_lesson(), indent=2))
        return 0

    only = None
    if a.system is not None and a.index is not None:
        sysname = a.system if a.system.startswith("(") else f"({a.system})"
        only = (sysname, a.index)

    doc = build(a.digits, a.verify_digits, only)
    text = json.dumps(doc, indent=1, sort_keys=False) + "\n"

    if a.stdout or only:
        print(text)
        return 0
    if a.check:
        cur = Path(a.out).read_text() if Path(a.out).exists() else ""
        if cur != text:
            print(f"STALE: {a.out} does not match a fresh scan", file=sys.stderr)
            return 1
        print(f"{a.out} is current")
        return 0

    Path(a.out).write_text(text)
    s = doc["summary"]
    print(f"wrote {a.out}")
    print(f"  states {s['loopy_states']}  loops {s['loops']}")
    print(f"  degrees {s['degree_counts']}")
    print(f"  galois  {s['galois_group_counts']}")
    for key in (
        "all_degrees_in_1_2_4",
        "all_two_elementary",
        "all_kernels_saturated",
        "all_symbolic_numeric_agree",
        "all_pslq_reverified",
        "all_pslq_confirm_exact",
        "all_multiquadratic_witnessed",
        "all_radicands_in_weight_group",
    ):
        print(f"  {key}: {s[key]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
