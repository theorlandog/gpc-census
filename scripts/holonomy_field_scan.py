#!/usr/bin/env python3
"""Census-wide scan of gauge-invariant loop holonomy fields.

For every certified INTERFERENCE state whose support carries loops (a nonzero
integer left-null lattice of the support incidence matrix), this computes the
gauge-invariant holonomies and the number field each holonomy cosine generates.

Setting. The single-particle gauge is U(1)^d: multiplying orbital m by
exp(i phi_m) multiplies the amplitude of determinant T by exp(i sum_{m in T}
phi_m). So for an integer vector k with k^T M = 0 (M the support incidence
matrix, M[T,m] = 1 iff m in T), the loop holonomy

    Phi(k) = sum_T k_T * arg(c_T)

is invariant under the whole gauge group, and cos(Phi(k)) is a gauge-invariant
real algebraic number attached to the state. The lattice of such k is the
integer left kernel of M; a basis of it is a basis of independent loops.

What gets certified per loop:

1. The kernel basis is SATURATED (all invariant factors 1), so the basis
   generates the full integer left kernel and no holonomy relation is missed.
2. cos(Phi) is computed symbolically from the closed form and cross-checked
   numerically at the working precision.
3. The minimal polynomial is obtained two independent ways: exactly with
   sympy minimal_polynomial, and numerically by PSLQ integer relation
   detection on the power vector.
4. THE PRECISION PROTOCOL (non-negotiable, see --precision-lesson): every
   PSLQ-recognized relation is re-verified at twice the working precision and
   the residual is recorded. A genuine relation's residual falls to the
   doubled precision floor; a spurious one stalls near the working precision.
   A relation that fails re-verification is deleted, never downgraded.
5. The Galois group of the minimal polynomial is computed with sympy
   galois_group (not inferred from evenness of the polynomial) and tested for
   2-elementarity, meaning isomorphic to (Z/2)^k.
6. The exact cosine is denested and its radicands extracted, so the
   multiquadratic conclusion is witnessed by explicit square roots of
   rationals rather than only by the Galois group; each radicand class in
   Q*/(Q*)^2 is then tested for membership in the group generated by the
   state weights and denominator. That last test is the STRONGER "square
   roots of rational monomials in the weights" sub-clause of the Holonomy
   Rationality conjecture, and it FAILS on 15 of the 82 loops. The failure is
   expected from the mechanism (the quadratic formula adjoins a square root
   of a discriminant, a polynomial and not a monomial in the weight data) and
   does not touch the multiquadratic conclusion. See docs/holonomy_rationality.md.

The scan also carries a TRISECTION AUDIT of the states the pipeline labels
TRISECTED, showing the label is a property of how the phase is printed rather
than of the state's arithmetic.

Usage:
  python scripts/holonomy_field_scan.py                     # write the artifact
  python scripts/holonomy_field_scan.py --check             # verify it is current
  python scripts/holonomy_field_scan.py --system '(3,10)' --index 17 --stdout
  python scripts/holonomy_field_scan.py --precision-lesson  # reproduce item 5
"""
