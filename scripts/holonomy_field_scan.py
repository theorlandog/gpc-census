# the precision lesson, reproduced as a certified artifact


def precision_lesson(system="(5,10)", index=144, loop=1):
    """Reproduce the PSLQ precision failure mode that produced a false
    counterexample in the exploratory session.

    At low working precision, PSLQ on a degree-7 power lattice returns a
    relation with large, structureless coefficients whose residual only reaches
    the working precision. Re-verification at doubled precision separates it
    from the true relation, whose residual reaches the doubled precision. This
    is the evidence behind the mandatory re-verification step.
    """
    rec = next(
        r
        for r in load_states()
        if r["system"] == system and r["index"] == index
    )
    cf = rec["closed_form"]
    dets = [tuple(t) for t in cf["support_dets"]]
    M, _ = incidence(dets)
    basis, _ = loop_basis(M)
    phases = [sp.arg(sp.sympify(p)) for p in cf["pretty"]]
    k = basis[loop]
    cos_exact = sp.simplify(sp.expand_trig(sp.cos(sum(k[i] * phases[i] for i in range(len(k))))))

    trials = []
    for dps in (20, 30, 40, 60, 120):
        mp.mp.dps = dps + 10
        val = to_mpf(cos_exact, dps + 25)
        rel = mp.pslq(
            [val**j for j in range(8)],
            maxcoeff=10**30,
            maxsteps=10**6,
            tol=mp.mpf(10) ** (-dps),
        )
        if not rel:
            trials.append({"working_digits": dps, "relation": None})
            continue
        mp.mp.dps = 2 * dps + 40
        v2 = to_mpf(cos_exact, 2 * dps + 60)
        res = abs(sum(mp.mpf(rel[j]) * v2**j for j in range(8)))
        trials.append(
            {
                "working_digits": dps,
                "verify_digits": 2 * dps,
                "relation": [int(c) for c in rel],
                "residual": mp.nstr(res, 5),
                "residual_log10": float(mp.log(res, 10)) if res > 0 else float("-inf"),
                "reaches_verify_precision": bool(res < mp.mpf(10) ** (-1.5 * dps)),
            }
        )
    mp.mp.dps = 15
    return {
        "system": system,
        "index": index,
        "loop": loop,
        "cos_exact": str(cos_exact),
        "true_min_poly": str(sp.minimal_polynomial(cos_exact, x)),
        "search_degree": 7,
        "trials": trials,
        "lesson": (
            "PSLQ hits at 20 to 40 digits are structureless and their residuals "
            "stall at the working precision; the true relation appears at 60 "
            "digits and its residual falls to the doubled precision. Every "
            "recognized relation must therefore be re-verified at at least "
            "double the working precision, with the residual recorded. A "
            "relation that fails re-verification is deleted, not downgraded."
        ),
    }


# --------------------------------------------------------------------------
# the trisection audit


def trisection_audit(loops_rows):
    """Audit the states the pipeline labels TRISECTED.

    scripts/reproduce_next_claims.py assigns the TRISECTED phase tier by a
    SYNTACTIC test on the printed closed form ("atan" and "/3" both present).
    This checks what is actually there: the degree over Q of every
    representative amplitude, and the minimal polynomial of every
    gauge-invariant loop holonomy of the same state.

    The written phase (pi + 3*atan(t))/3 equals pi/3 + atan(t); the division by
    three cancels, so no cube root survives the simplification. The audit
    records this rather than asserting it.
    """
    by_state = {}
    for r in loops_rows:
        by_state.setdefault((r["system"], r["index"]), []).append(r)

    out = []
    for rec in load_states():
        pretty = [str(p) for p in rec["closed_form"]["pretty"]]
        joined = " ".join(pretty)
        if not (re.search(r"\bI\b", joined) and "atan" in joined and "/3" in joined):
            continue
        degrees = set()
        for p in pretty:
            e = sp.sympify(p)
            e = sp.expand(sp.re(e)) + sp.I * sp.expand(sp.im(e))
            degrees.add(int(sp.minimal_polynomial(sp.simplify(e), x).as_poly(x).degree()))
        loops = by_state.get((rec["system"], rec["index"]), [])
        out.append(
            {
                "system": rec["system"],
                "index": rec["index"],
                "amplitude_degrees_over_Q": sorted(degrees),
                "all_degrees_are_powers_of_two": all(d & (d - 1) == 0 for d in degrees),
                "any_degree_divisible_by_three": any(d % 3 == 0 for d in degrees),
                "holonomy_min_polys": [loop["min_poly"] for loop in loops],
                "holonomy_degrees": [loop["degree"] for loop in loops],
                "holonomy_galois_groups": [loop["galois_group"] for loop in loops],
            }
        )
    return {
        "tier_definition": (
            "syntactic: the printed closed form contains both 'atan' and '/3' "
            "(scripts/reproduce_next_claims.py::two_block_phase_census)"
        ),
        "states": len(out),
        "no_cubic_anywhere": all(
            not s["any_degree_divisible_by_three"] and s["all_degrees_are_powers_of_two"]
            for s in out
        ),
        "all_holonomies_degree_1_2_4": all(
            all(d in (1, 2, 4) for d in s["holonomy_degrees"]) for s in out
        ),
        "finding": (
            "The TRISECTED tier is an artifact of how the amplitude phase is "
            "printed, not a phase-complexity tier. (pi + 3*atan(t))/3 reduces "
            "to pi/3 + atan(t); every representative amplitude of every state "
            "in the tier has 2-power degree over Q, and every gauge-invariant "
            "loop holonomy of those states is rational or multiquadratic. No "
            "cubic subextension occurs anywhere in the class."
        ),
        "records": out,
    }


