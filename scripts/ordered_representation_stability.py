def _flip_row(coeffs: tuple[int, ...], rhs: int) -> tuple[tuple[int, ...], int]:
    """Particle-hole image of an affine row: lambda_i -> 1 - lambda_{d+1-i}."""

    d = len(coeffs)
    return tuple(-coeffs[d - 1 - i] for i in range(d)), rhs - sum(coeffs)


def _flip_vertex(v: Vertex) -> Vertex:
    """Particle-hole image of an ordered spectrum, still dominant-ordered."""

    return tuple(1 - x for x in reversed(v))


def load_systems() -> dict[tuple[int, int], dict]:
    """Return every system this campaign can evaluate, exactly.

    Primary systems are the nine published tables.  A dual system ``(d-n, d)``
    is derived from ``(n, d)`` by the particle-hole bijection, which is exact
    and is already the census convention in ``gpc_census.constraints``.  Duals
    are marked so that no count can silently treat them as new evidence.
    """

    table = _table()
    systems: dict[tuple[int, int], dict] = {}
    for key, payload in table.items():
        n, d = (int(part) for part in key.split(","))
        rows = [(tuple(iq["coeffs"]), iq["rhs"]) for iq in payload["inequalities"]]
        vertices = [
            tuple(Fraction(x) for x in rec["spectrum"])
            for rec in json.loads((DATA / "vertices" / f"vertices_{n}_{d}.json").read_text())
        ]
        systems[n, d] = {
            "rows": rows,
            "vertices": vertices,
            "primary": True,
            "equalities": len(payload["equalities"]),
            "source": payload["source"],
        }
    for (n, d), payload in list(systems.items()):
        dual = (d - n, d)
        if dual in systems:
            continue
        systems[dual] = {
            "rows": [_flip_row(c, b) for c, b in payload["rows"]],
            "vertices": [_flip_vertex(v) for v in payload["vertices"]],
            "primary": False,
            "equalities": payload["equalities"],
            "source": payload["source"] + " (particle-hole dual)",
        }
    return systems


