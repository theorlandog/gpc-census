def rho(tau: Tau) -> Tau | None:
    """Terminal restriction, contravariant.  None when the image is trivial."""

    head = tau[:-1]
    if len(set(head)) <= 1:
        return None
    return primitive_tau(head)


def rho_drop(tau: Tau, j: int) -> Tau | None:
    """Restriction along the injection omitting coordinate j (0-indexed)."""

    head = tau[:j] + tau[j + 1:]
    if len(set(head)) <= 1:
        return None
    return primitive_tau(head)


def _clear(values: list[Fraction]) -> tuple[int, ...]:
    denominator = reduce(lambda a, b: a * b // gcd(a, b), [v.denominator for v in values], 1)
    return tuple(int(v * denominator) for v in values)


def pi_pad(tau: Tau, vertices_next: list[Vertex]) -> Tau | None:
    """Tight padding extension, covariant: the strongest valid one-mode extension.

    ``t*`` is the largest last entry keeping the row valid on the bigger slice.
    Returns None when no vertex of the target slice occupies the new mode, in
    which case tightness is not defined.
    """

    d = len(tau)
    bounds = [
        -dot(tau, v[:d]) / v[d]
        for v in vertices_next
        if v[d] > 0
    ]
    if not bounds:
        return None
    t_star = min(bounds)
    entries = [Fraction(t) for t in tau] + [t_star]
    return primitive_tau(_clear(entries))


def phi_core(tau: Tau, n_source: int) -> Tau | None:
    """Frozen-core restriction from (n_source, d) to (n_source - 1, d - 1).

    On affine forms this drops the first coordinate and lowers the right-hand
    side by its coefficient.  On primitive taus it is the exact linear formula
    ``tau'_i = (n_source - 1) * tau_i + tau_1``, derived by substituting the
    gauge-free representative on both sides.
    """

    n_target = n_source - 1
    if n_target <= 0:
        return None
    image = [n_target * t + tau[0] for t in tau[1:]]
    if len(set(image)) <= 1:
        return None
    return primitive_tau(tuple(image))


def psi_core(tau: Tau, n: int, vertices_next: list[Vertex]) -> Tau | None:
    """Tight frozen-core extension from (n, d) to (n + 1, d + 1).

    The extension is ``c*lambda_1 + a.lambda_{2..} <= b + c`` with ``c`` as
    small as validity allows, which is the strongest choice because
    ``c*(lambda_1 - 1) <= 0`` weakens the row as ``c`` grows.
    """

    row = constraint_from_tau(tau, n)
    a, b = row.coeffs, row.rhs
    bounds = [
        (sum((Fraction(ai) * x for ai, x in zip(a, v[1:])), Fraction(0)) - b) / (1 - v[0])
        for v in vertices_next
        if v[0] < 1
    ]
    if not bounds:
        return None
    c_star = max(bounds)
    scale = c_star.denominator
    coeffs = (int(c_star * scale),) + tuple(ai * scale for ai in a)
    rhs = b * scale + int(c_star * scale)
    return tau_from_constraint(IntegralConstraint(coeffs, rhs), n + 1)


def delta_ph(tau: Tau, n: int) -> Tau:
    """Particle-hole duality, rank preserving, involutive on primitive taus."""

    row = constraint_from_tau(tau, n)
    coeffs, rhs = _flip_row(row.coeffs, row.rhs)
    return tau_from_constraint(IntegralConstraint(coeffs, rhs), len(tau) - n)


