def width(tau: Tau) -> int:
    """Smallest k with tau constant after position k; gauge free.

    ``width(tau) <= k`` holds exactly when the row has an affine representative
    supported on the first k coordinates, so width is the rank from which a row
    could possibly be pulled back.
    """

    k = len(tau)
    while k > 0 and tau[k - 1] == tau[-1]:
        k -= 1
    return k


def spread(tau: Tau) -> int:
    return max(tau) - min(tau)


def affine_height(tau: Tau, n: int) -> int:
    row = constraint_from_tau(tau, n)
    return max(max(abs(c) for c in row.coeffs), abs(row.rhs))


def dot(tau: Tau, v: Vertex) -> Fraction:
    return sum((Fraction(t) * x for t, x in zip(tau, v)), Fraction(0))


def is_valid(tau: Tau, vertices: list[Vertex]) -> bool:
    """A homogeneous row is valid iff it holds at every vertex of the slice."""

    return all(dot(tau, v) <= 0 for v in vertices)


def is_chamber_row(tau: Tau, n: int) -> bool:
    """Whether the row is one of the structural dominant-chamber inequalities."""

    d = len(tau)
    row = constraint_from_tau(tau, n)
    coeffs, rhs = row.coeffs, row.rhs
    if tau == (0,) * (d - 1) + (-1,):          # lambda_d >= 0
        return True
    for i in range(d - 1):                      # lambda_i >= lambda_{i+1}
        pattern = [0] * d
        pattern[i], pattern[i + 1] = -1, 1
        if tau == primitive_tau(tuple(pattern)):
            return True
    if coeffs == tuple([1] + [0] * (d - 1)) and rhs == 1:   # lambda_1 <= 1
        return True
    return False


